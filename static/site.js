function readPreference(key, fallback) {
    try {
        return window.localStorage.getItem(key) || fallback;
    } catch {
        return fallback;
    }
}

function savePreference(key, value) {
    try {
        window.localStorage.setItem(key, value);
    } catch {
        // Preferences remain usable for the current page if storage is blocked.
    }
}

function applyLanguage(language) {
    const translations = T[language] || T.ru;
    document.documentElement.lang = language;
    document.querySelectorAll('[data-t]').forEach((element) => {
        const translated = translations[element.dataset.t];
        if (translated === undefined) return;
        const arrow = element.querySelector('b');
        if (arrow && element.firstChild && element.firstChild.nodeType === Node.TEXT_NODE) {
            element.firstChild.textContent = translated + ' ';
            return;
        }
        element.innerHTML = translated;
    });
    document.querySelectorAll('[data-lang]').forEach((button) => {
        const selected = button.dataset.lang === language;
        button.classList.toggle('selected', selected);
        button.setAttribute('aria-pressed', selected ? 'true' : 'false');
    });
    savePreference('site-language', language);
    window.dispatchEvent(new Event('site-language-change'));
}

function applyTheme(theme) {
    const selectedTheme = theme === 'dark' ? 'dark' : 'light';
    document.documentElement.dataset.theme = selectedTheme;
    savePreference('site-theme', selectedTheme);
    const themeColor = selectedTheme === 'dark' ? '#201e21' : '#f7f6f5';
    const themeMeta = document.querySelector('meta[name="theme-color"]');
    if (themeMeta) themeMeta.setAttribute('content', themeColor);
    const button = document.getElementById('theme-toggle');
    if (button) {
        button.setAttribute('aria-pressed', selectedTheme === 'dark' ? 'true' : 'false');
        button.setAttribute('aria-label', selectedTheme === 'dark' ? 'Включить светлую тему' :
            'Включить тёмную тему');
    }
}

function startGallery() {
    const slides = Array.from(document.querySelectorAll('.hero-slide'));
    if (!slides.length) return;
    const dots = Array.from(document.querySelectorAll('[data-slide]'));
    const caption = document.getElementById('gallery-caption');
    const labels = {
        ru: ['01 / УЧЁБА БЕЗ ГРАНИЦ', '02 / ИДЕИ В ДЕЙСТВИИ', '03 / ЛЮДИ СОЗДАЮТ БУДУЩЕЕ'],
        kk: ['01 / ШЕКСІЗ БІЛІМ', '02 / ИДЕЯ ІСКЕ АСАДЫ', '03 / БОЛАШАҚТЫ АДАМДАР ҚҰРАДЫ'],
        en: ['01 / LEARNING WITHOUT LIMITS', '02 / IDEAS IN ACTION',
            '03 / PEOPLE SHAPING TOMORROW'
        ]
    };
    let currentSlide = 0;

    function showSlide(index) {
        currentSlide = index;
        slides.forEach((slide, position) => slide.classList.toggle('active', position === index));
        dots.forEach((dot, position) => dot.classList.toggle('active', position === index));
        if (caption) {
            const language = readPreference('site-language', 'ru');
            caption.textContent = labels[language][index];
        }
    }
    dots.forEach((dot, index) => {
        dot.addEventListener('click',
            () => showSlide(index));
    });
    showSlide(0);
    window.addEventListener('site-language-change',
        () => showSlide(currentSlide));
    window.setInterval(() => showSlide((currentSlide + 1) % slides.length), 6500);
}

function initializePageControls() {
    applyLanguage(readPreference('site-language', 'ru'));
    applyTheme(readPreference('site-theme', 'light'));
    startGallery();
    document.addEventListener('click',
        (event) => {
            const languageButton = event.target.closest('[data-lang]');
            if (languageButton) {
                applyLanguage(languageButton.dataset.lang);
                return;
            }
            const themeButton = event.target.closest('#theme-toggle');
            if (themeButton) {
                const nextTheme = document.documentElement.dataset.theme === 'dark' ? 'light' :
                    'dark';
                applyTheme(nextTheme);
                return;
            }
            const menuButton = event.target.closest('#menu-toggle');
            if (menuButton) {
                document.getElementById('nav').classList.toggle('open');
                return;
            }
            if (event.target.closest('#nav a')) {
                document.getElementById('nav').classList.remove('open');
            }
        });
}
if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', initializePageControls);
} else {
    initializePageControls();
}
